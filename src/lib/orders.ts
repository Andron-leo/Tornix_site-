export function missingMessage(have: Record<string, boolean>): string {
  const miss = ASK_CLIENT.filter((q) => !have[q.id]).map((q) => q.label);
  if (miss.length === 0) {
    return "Дякую, файли на місці. Порахуємо і повернемось із ціною сьогодні–завтра.";
  }
  return [
    "Доброго дня.",
    "Щоб порахувати замовлення, надішліть, будь ласка:",
    ...miss.map((t, i) => `${i + 1}. ${t}`),
    "Як будуть файли — ціна того ж дня.",
  ].join("\n");
}

